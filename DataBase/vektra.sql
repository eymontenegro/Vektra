
-- =========================================================
-- VEKTRA - DATABASE SCHEMA
-- PostgreSQL
-- ADVERTENCIA: elimina y recrea las seis tablas.
-- =========================================================

BEGIN;

-- =========================================================
-- 1. DROP TABLES
-- Se eliminan primero las tablas dependientes.
-- CASCADE elimina dependencias adicionales de PostgreSQL.
-- =========================================================

DROP TABLE IF EXISTS tickets CASCADE;
DROP TABLE IF EXISTS routes CASCADE;
DROP TABLE IF EXISTS drivers CASCADE;
DROP TABLE IF EXISTS vehicles CASCADE;
DROP TABLE IF EXISTS stations CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- =========================================================
-- 2. USERS
-- Administradores, pasajeros y usuarios conductores.
-- =========================================================

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'PASSENGER',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_role
        CHECK (role IN ('ADMIN', 'PASSENGER', 'DRIVER'))
);

-- =========================================================
-- 3. DRIVERS
-- Los conductores no inician sesión, por eso no dependen de users.
-- Campos de Person (id, nationalId, name, lastName)
-- más licencia, teléfono, estado y la ruta asignada.
-- La ruta se guarda por su id, no por su texto.
-- =========================================================

CREATE TABLE drivers (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    national_id    VARCHAR(12)  NOT NULL,
    name           VARCHAR(100) NOT NULL,
    last_name      VARCHAR(100) NOT NULL,
    license_number VARCHAR(50),
    phone          VARCHAR(25),
    status         VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    route_id       BIGINT       NOT NULL,

    CONSTRAINT pk_drivers PRIMARY KEY (id),
    CONSTRAINT uq_drivers_national_id UNIQUE (national_id),
    CONSTRAINT uq_drivers_license UNIQUE (license_number),
    CONSTRAINT chk_drivers_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- =========================================================
-- 4. VEHICLES
-- La línea se guarda con el nombre de la constante de LineColor
-- (RED, BLUE, GREEN, YELLOW) y el conductor por su id en drivers.
-- =========================================================

CREATE TABLE vehicles (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    plate     VARCHAR(15) NOT NULL,
    brand     VARCHAR(60),
    model     VARCHAR(60),
    year      INTEGER     NOT NULL,
    capacity  SMALLINT    NOT NULL,
    line      VARCHAR(20) NOT NULL,
    driver_id BIGINT      NOT NULL,

    CONSTRAINT pk_vehicles PRIMARY KEY (id),
    CONSTRAINT uq_vehicles_plate UNIQUE (plate),
    CONSTRAINT chk_vehicles_capacity CHECK (capacity > 0),
    CONSTRAINT chk_vehicles_year CHECK (year >= 1900),
    CONSTRAINT chk_vehicles_line CHECK (line IN ('RED', 'BLUE', 'GREEN', 'YELLOW')),
    CONSTRAINT fk_vehicles_driver FOREIGN KEY (driver_id) REFERENCES drivers(id)
);

-- =========================================================
-- 5. STATIONS
-- Estaciones de origen y destino.
-- =========================================================

CREATE TABLE stations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(120) NOT NULL,
    address VARCHAR(255) NOT NULL,
    city VARCHAR(100) NOT NULL,
    department VARCHAR(100),
    latitude NUMERIC(10, 7),
    longitude NUMERIC(10, 7),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_stations PRIMARY KEY (id),

    CONSTRAINT chk_stations_latitude
        CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),

    CONSTRAINT chk_stations_longitude
        CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

-- =========================================================
-- 6. ROUTES
-- Relaciona estaciones, conductores y vehículos.
-- Si se elimina una estación, conductor o vehículo,
-- se eliminan las rutas afectadas.
-- =========================================================

CREATE TABLE routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    origin_station_id BIGINT NOT NULL,
    destination_station_id BIGINT NOT NULL,
    driver_id BIGINT,
    vehicle_id BIGINT,
    departure_time TIMESTAMP NOT NULL,
    arrival_time TIMESTAMP,
    price NUMERIC(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_routes PRIMARY KEY (id),

    CONSTRAINT fk_routes_origin
        FOREIGN KEY (origin_station_id)
        REFERENCES stations(id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    CONSTRAINT fk_routes_destination
        FOREIGN KEY (destination_station_id)
        REFERENCES stations(id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    CONSTRAINT fk_routes_driver
        FOREIGN KEY (driver_id)
        REFERENCES drivers(id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    CONSTRAINT fk_routes_vehicle
        FOREIGN KEY (vehicle_id)
        REFERENCES vehicles(id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    CONSTRAINT chk_routes_different_stations
        CHECK (origin_station_id <> destination_station_id),

    CONSTRAINT chk_routes_price
        CHECK (price >= 0),

    CONSTRAINT chk_routes_times
        CHECK (arrival_time IS NULL OR arrival_time > departure_time),

    CONSTRAINT chk_routes_status
        CHECK (
            status IN (
                'SCHEDULED',
                'IN_PROGRESS',
                'COMPLETED',
                'CANCELLED'
            )
        )
);

-- =========================================================
-- 7. TICKETS
-- Cada ticket pertenece a un usuario y una ruta.
-- =========================================================

CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ticket_code VARCHAR(40) NOT NULL,
    user_id BIGINT NOT NULL,
    route_id BIGINT NOT NULL,
    seat_number SMALLINT NOT NULL,
    price NUMERIC(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'RESERVED',
    purchase_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_tickets PRIMARY KEY (id),
    CONSTRAINT uq_tickets_code UNIQUE (ticket_code),

    -- Un asiento no puede asignarse dos veces en la misma ruta.
    CONSTRAINT uq_tickets_route_seat
        UNIQUE (route_id, seat_number),

    CONSTRAINT fk_tickets_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    CONSTRAINT fk_tickets_route
        FOREIGN KEY (route_id)
        REFERENCES routes(id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    CONSTRAINT chk_tickets_seat
        CHECK (seat_number > 0),

    CONSTRAINT chk_tickets_price
        CHECK (price >= 0),

    CONSTRAINT chk_tickets_status
        CHECK (status IN ('RESERVED', 'PAID', 'CANCELLED', 'USED'))
);

-- =========================================================
-- 8. INDEXES
-- Índices para acelerar consultas y búsquedas habituales.
-- Las restricciones UNIQUE ya crean sus propios índices.
-- =========================================================

CREATE INDEX idx_routes_departure_time
    ON routes(departure_time);

CREATE INDEX idx_routes_status
    ON routes(status);

CREATE INDEX idx_routes_driver
    ON routes(driver_id);

CREATE INDEX idx_routes_vehicle
    ON routes(vehicle_id);

CREATE INDEX idx_routes_origin
    ON routes(origin_station_id);

CREATE INDEX idx_routes_destination
    ON routes(destination_station_id);

CREATE INDEX idx_tickets_user
    ON tickets(user_id);

